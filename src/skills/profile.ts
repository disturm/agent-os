/**
 * Skill: профиль пользователя.
 *
 * Раньше `data/profile.md` целиком уезжал в промпт коуча при старте. Теперь файл читает
 * сам агент — и только когда он ему нужен. Модуль знает про один файл и ничего больше:
 * ни про harness, ни про других агентов.
 */

import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { tool } from '@openai/agents';
import { z } from 'zod';

export const getProfile = tool({
  name: 'getProfile',
  description: [
    'Возвращает профиль пользователя как markdown: возраст, рост и вес, характер работы,',
    'цели, ограничения (травмы, аллергии, пищевые непереносимости), предпочтения в еде и тренировках,',
    'текущие привычки.',
    'Вызывай ПЕРВЫМ в любой задаче про питание, тренировки, режим дня или покупки:',
    'без ограничений из профиля план может оказаться опасным (аллергия, травма) или невыполнимым.',
    'Параметров нет, данные за прогон не меняются — второй раз вызывать незачем.',
  ].join(' '),
  parameters: z.object({}),
  execute: async () => readFileSync(join(process.cwd(), 'data', 'profile.md'), 'utf8'),
});
