/**
 * Skill: каркасы тренировок.
 *
 * Шаблоны захардкожены намеренно: это не база упражнений и не генератор, а четыре
 * заготовки, чтобы агент не сочинял структуру занятия с нуля. Ограничения пользователя
 * (травмы, доступный инвентарь) шаблон не учитывает — их агент берёт из `getProfile`
 * и правит план сам.
 */

import { tool } from '@openai/agents';
import { z } from 'zod';

const TEMPLATES = {
  fat_loss: `## Шаблон: снижение веса (50–55 минут)
- Разминка: 8 минут — велотренажёр или эллипс в спокойном темпе, суставная разминка.
- Основная часть: круговая, 3 круга по 4 упражнения на всё тело, 12–15 повторов, отдых 60 секунд между кругами.
- Добивка: 10 минут кардио на пульсе, при котором можно говорить фразами.
- Заминка: 5 минут растяжки бёдер, спины, груди.
- Ориентир нагрузки: тяжело к последним повторам, но техника не рассыпается.`,

  strength: `## Шаблон: сила и мышцы (45–60 минут)
- Разминка: 8 минут — кардио плюс два подхода с пустым весом на первое упражнение.
- Основная часть: 2 базовых упражнения по 4 подхода на 6–8 повторов, отдых 2 минуты.
- Подсобка: 2 упражнения по 3 подхода на 10–12 повторов, отдых 90 секунд.
- Заминка: 5 минут растяжки поработавших мышц.
- Ориентир нагрузки: в запасе 1–2 повтора в каждом подходе.`,

  endurance: `## Шаблон: выносливость (40–50 минут)
- Разминка: 10 минут в лёгком темпе, дыхание ровное.
- Основная часть: 25–30 минут равномерной работы (плавание, велотренажёр, быстрая ходьба в горку).
- Финиш: 3 ускорения по 1 минуте с 2 минутами восстановления между ними.
- Заминка: 5 минут спокойного темпа плюс растяжка.
- Ориентир нагрузки: разговор даётся короткими фразами, дыхание не срывается.`,

  recovery: `## Шаблон: восстановление и мобильность (25–35 минут)
- Разминка: 5 минут спокойной ходьбы или лёгкого кардио.
- Основная часть: 15 минут мобильности — тазобедренные суставы, грудной отдел, голеностопы, по 2 подхода на зону.
- Стабилизация: 3 упражнения на корпус в статике по 30–40 секунд.
- Заминка: 5 минут дыхания и растяжки.
- Ориентир нагрузки: без боли и без «до отказа», это день разгрузки.`,
} as const;

export const suggestWorkoutTemplate = tool({
  name: 'suggestWorkoutTemplate',
  description: [
    'Возвращает готовый каркас одной тренировки под выбранную цель: разминка, основная часть, заминка,',
    'ориентир по нагрузке.',
    'Вызывай, когда в плане нужна тренировка и понятна её цель на этот день.',
    'Шаблон — это заготовка, а не итог: конкретные упражнения подбирай сам, с оглядкой на ограничения из getProfile',
    '(травмы, запрещённые движения) и на нагрузку последних дней из getRecentLog.',
    'Если целей на день две, вызови инструмент дважды и объедини.',
  ].join(' '),
  parameters: z.object({
    goal: z
      .enum(['fat_loss', 'strength', 'endurance', 'recovery'])
      .describe(
        'Цель тренировки: fat_loss — снижение веса, круговая работа; strength — сила и мышцы, база с отдыхом; ' +
          'endurance — выносливость, длительное кардио; recovery — лёгкий день, мобильность и восстановление.',
      ),
  }),
  execute: async ({ goal }) => TEMPLATES[goal],
});
