/**
 * Имена инструментов, вызванных агентом за один прогон `run()`.
 *
 * Инструменты у агента появились, а видимости — нет: снаружи прогон по-прежнему выглядит
 * как «пришёл текст плана». Модуль превращает элементы прогона в плоский список имён,
 * по которому видно, откуда агент взял данные. Ничего не решает и никуда не пишет —
 * порядок и накопление остаются за оркестратором.
 */

import type { RunItem } from '@openai/agents';

/**
 * Имена вызовов в порядке появления. Повторы не схлопываются: два `read_profile` — два факта.
 *
 * MCP-инструменты попадают сюда наравне с локальными и без пометок: SDK превращает их
 * в обычные function tools, и в списке они выглядят так же — `read_profile` рядом с
 * `generateShoppingList`. Разделение по происхождению — забота UI, а не этого модуля.
 */
export function toolCallNames(items: RunItem[]): string[] {
  return items
    .filter((item) => item.type === 'tool_call_item')
    // У функциональных вызовов есть имя; у остальных типов (computer use и прочее,
    // которых у нас нет) остаётся хотя бы тип — молча терять вызов нельзя.
    .map((item) => ('name' in item.rawItem ? item.rawItem.name : item.rawItem.type));
}
