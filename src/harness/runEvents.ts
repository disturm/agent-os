/**
 * Что harness рассказывает о себе, пока работает: формат событий прогона и приёмник.
 *
 * Отдельный модуль по той же причине, что и `traceRun.ts`: формат наблюдения — это
 * самостоятельная ответственность, и ни оркестратор, ни роут не должны описывать его у себя.
 * Про HTTP, стриминг и AI SDK модуль не знает; про `AgentResult` — тоже, и намеренно:
 * итог прогона наблюдателю отдаёт `runHealthAgent` обычным возвратом, а событиями идёт
 * только то, что иначе видно не было бы (см. `docs/spec9.md`).
 *
 * События — диагностика, а не управление: harness не спрашивает у приёмника разрешения
 * и не смотрит, что тот вернул. Прогон без `onEvent` идёт ровно тем же путём, поэтому
 * `POST /api/agent/run`, CLI, replay и evals не заметили появления этого модуля.
 */

import type { Review } from './validateReview';

export type RunEvent =
  /**
   * Роутер OS выбрал модуль (`docs/specA.md`). Приходит первым, до всего остального:
   * классификация идёт до прогона и решает, с каким промптом и набором инструментов он
   * пойдёт. `general` — уверенности не хватило, специализации нет.
   *
   * Событие живёт здесь, а не в `src/os/`, по той же причине, что и остальные: формат
   * наблюдения за прогоном описан в одном месте, кто бы его ни отправлял.
   */
  | { type: 'module'; module: string; confidence: number }
  /** Коуч начал круг. `round` 1 — черновик, дальше — доработка по замечаниям. */
  | { type: 'coach_start'; round: number }
  /** Круг коуча закончился: текст плана готов, инструментов он больше не зовёт. */
  | { type: 'coach_end'; round: number }
  /**
   * Инструмент вызван. Приходит в момент вызова, а не после круга: `toolCallNames`
   * разбирает `result.newItems` уже готового прогона, и для живого таймлайна это поздно.
   * `source` — имя MCP-сервера либо `local`, в той же форме, что и в `toolCalls`.
   */
  | { type: 'tool_call'; name: string; source: string }
  /** Инструмент вернул результат: дальше слово снова у модели. */
  | { type: 'tool_result'; name: string }
  /** Обращение к базе знаний. Приходит между `tool_call` и `tool_result` того же поиска. */
  | { type: 'retrieval'; query: string; headings: string[] }
  | { type: 'review_start'; round: number }
  | { type: 'review_done'; round: number; review: Review }
  /** Начался шаг фиксации: у агента появились необратимые инструменты. */
  | { type: 'saving' };

export type OnEvent = (event: RunEvent) => void;

/** Приёмник по умолчанию: без него каждая точка эмиссии обрастала бы проверкой на undefined. */
export const IGNORE_EVENTS: OnEvent = () => {};
