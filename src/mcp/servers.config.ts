/**
 * Список MCP-серверов прогона. Единственное место, где решается, что подключено
 * и какие инструменты кому достаются.
 *
 * Смысл файла (`docs/spec7.md`): интеграция чужого сервера — это запись здесь, а не код.
 * Ни harness, ни агенты про эти строки не знают: они получают готовый список инструментов.
 * Новый сервер добавляется одной записью, отключается — сменой `enabled` на `false`;
 * править `src/harness/*` при этом не нужно ни в том, ни в другом случае.
 *
 * Свой сервер и чужие лежат в одном массиве намеренно: для агента разницы между ними нет,
 * и видно, что «наш markdown» — просто ещё одна строка конфига.
 *
 * ВАЖНО: `.env` должен быть загружен до импорта этого модуля — `env` ниже читается на
 * загрузке. В CLI это делает `import 'dotenv/config'` первой строкой `index.ts`,
 * в приложении — сам Next.
 */

import { join } from 'node:path';

export type McpServerConfig = {
  /** Имя сервера. Оно же уезжает в `toolCalls` префиксом источника: `[weather] weather_forecast`. */
  name: string;
  command: string;
  args: string[];
  /** Переменные окружения процесса сервера. Дописываются к безопасному минимуму (PATH и прочее). */
  env?: Record<string, string | undefined>;
  enabled: boolean;
  /**
   * Имя переменной окружения, наличие которой включает сервер при `enabled: false`.
   * Нет переменной — сервер молча пропускается, ошибкой это не считается.
   */
  enabledWhenEnv?: string;
  /** Инструменты, которые получает коуч на черновых кругах. Пусто — сервер в этой фазе не участвует. */
  draftTools?: string[];
  /**
   * Инструменты, которые выдаются только после `approve`. Сюда идёт всё необратимое:
   * запись плана, файл на диске, страница в Notion.
   */
  approvedTools?: string[];
};

